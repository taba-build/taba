/// The first line of every file taba writes, so it only ever replaces or deletes its own.
const MARKER: &str = "@generated by taba-build";

/// The TypeScript clients for an app's procedures, one package for each crate.
#[derive(Debug, Default)]
pub struct Build {
    lists: Vec<(Procedures, PathBuf)>,
}

impl Build {
    /// A build with no packages.
    pub fn new() -> Self {
        Self::default()
    }

    /// Gives the crate `procedures` was started in a package, with its client in `directory`.
    ///
    /// taba replaces or deletes only the files it wrote in `directory`. Crates
    /// and directories pair one to one.
    pub fn package(mut self, procedures: Procedures, directory: impl Into<PathBuf>) -> Self {
        self.lists.push((procedures, directory.into()));
        self
    }

    /// Writes each package's client.
    ///
    /// Each procedure goes in its own crate's package, whichever list holds it.
    ///
    /// # Errors
    ///
    /// When crates and directories don't pair one to one, a procedure's crate has no package, a
    /// procedure's name can't name a JavaScript function, a client would replace a file taba
    /// didn't write, or a client's directory can't be read or written.
    pub fn write(self) -> Result<(), WriteError> {
        for package in self.packages()?.values() {
            write(package.directory, package.files())?;
        }
        Ok(())
    }

    /// Each crate's package, holding its procedures from every list.
    fn packages(&self) -> Result<BTreeMap<CrateCrate, Package<'_>>, WriteError> {
        let mut packages = BTreeMap::new();
        let mut crates = BTreeMap::new();
        for (procedures, directory) in &self.lists {
            let crate_ = procedures.__crate();
            let package = Package { crate_, directory, procedures: BTreeMap::new() };
            let package = packages.entry(crate_).or_insert(package);
            let owner = crates.entry(directory).or_insert(crate_);
            if package.directory != directory || *owner != crate_ {
                return Err(WriteError::unpaired(crate_, directory));
            }
        }
        let declarations =
            self.lists.iter().flat_map(|(procedures, _)| procedures.__declarations());
        for declaration in declarations {
            let named = (declaration.named)();
            let function = function_name(named);
            // every module runs in strict mode, which can't bind these either
            if is_reserved_keyword(&function) || matches!(&*function, "eval" | "arguments") {
                return Err(WriteError::reserved(named.path(), function));
            }
            let crate_ = named.crate_();
            let Some(package) = packages.get_mut(crate_) else {
                return Err(WriteError::unpackaged(named.path(), crate_));
            };
            let module = package.procedures.entry(named.module_path).or_default();
            module.insert(named.name, declaration);
        }
        Ok(packages)
    }
}

/// One crate's procedures, and the directory its client goes in.
struct Package<'b> {
    crate_: CrateCrate,
    directory: &'b Path,

    /// By module path, then name.
    procedures: BTreeMap<&'static str, BTreeMap<&'static str, &'b procedure::Declaration>>,
}

impl Package<'_> {
    /// The client's files, by path within its directory.
    ///
    /// Every type goes in the root's `index.d.ts`, and each module with procedures gets an
    /// `index.js` and `index.d.ts` of its own.
    fn files(&self) -> Vec<(PathBuf, String)> {
        let mut types = Declarations::new(self.crate_);
        for procedure in self.procedures.values().flat_map(BTreeMap::values) {
            types.add(&Shape::Reference(procedure.named, &[]));
            let (ReplyShape::Once(value) | ReplyShape::Strand(value)) = procedure.reply;
            types.add(value);
            types.add(procedure.error);
        }
        let mut files = Vec::new();
        let mut root = Vec::new();
        for (module_path, procedures) in &self.procedures {
            let procedures: Vec<_> = procedures.values().copied().collect();
            let segments: Vec<_> = module_path.split("::").skip(1).collect();
            let directory: PathBuf = segments.iter().collect();
            files.push((directory.join("index.js"), script(&procedures)));
            if segments.is_empty() {
                root = procedures;
            } else {
                let types = format!("{}index.js", "../".repeat(segments.len()));
                let functions = declarations_file(self.crate_, None, &types, &procedures);
                files.push((directory.join("index.d.ts"), functions));
            }
        }
        let root = declarations_file(self.crate_, Some(&types), "./index.js", &root);
        files.push(("index.d.ts".into(), root));
        files
    }
}

/// The request's name, in camelCase.
fn function_name(named: &Named) -> String {
    let mut chars = named.name.chars();
    let first = chars.next().map(|first| first.to_ascii_lowercase());
    first.into_iter().chain(chars).collect()
}

/// Whether a procedure can fail.
fn fallible(procedure: &procedure::Declaration) -> bool {
    !matches!(procedure.error, Shape::Never)
}

/// A module's `index.d.ts`, declaring `types` when it's the root and each of `procedures`.
fn declarations_file(
    crate_: CrateCrate,
    types: Option<&Declarations>,
    specifier: &str,
    procedures: &[&procedure::Declaration],
) -> String {
    let allocator = Allocator::default();
    let ast = AstBuilder::new(&allocator);
    let mut printer = Printer::new(&ast, crate_);
    let marker = printer.comments.line(MARKER);
    let mut body = types.map(|types| types.modules(&mut printer)).unwrap_or_default();
    body.extend(procedures.iter().map(|procedure| signature(&mut printer, procedure)));
    let mut imports = vec![printer.import_types(marker, specifier)];
    if procedures.iter().any(|procedure| fallible(procedure)) {
        imports.push(import(&ast, SPAN, ImportOrExportKind::Type, [("Result", "$Result")]));
    }
    Codegen::new().build(&printer.program(imports, body)).code
}

/// `export declare function buy(request: ..., options?: { signal?: AbortSignal }): Promise<...>;`
fn signature<'a>(printer: &mut Printer<'a>, procedure: &procedure::Declaration) -> Statement<'a> {
    let ast = printer.ast;
    let named = (procedure.named)();
    let span = printer.comments.jsdoc(named.docs);
    let function = ast.allocator().alloc_str(&function_name(named));

    // only a type's own declaration holds parameters or parts, so any `named` prints these
    let mut types = Declaring { file: printer, named };

    let request = types.ts(&Shape::Reference(procedure.named, &[]));
    let (ReplyShape::Once(value) | ReplyShape::Strand(value)) = procedure.reply;
    let mut value = types.ts(value);
    if fallible(procedure) {
        let error = types.ts(procedure.error);
        value = reference(ast, "$Result", [value, error]);
    }
    let (last, returned) = if let ReplyShape::Strand(_) = procedure.reply {
        let signal = parameter(ast, "signal", Some(reference(ast, "AbortSignal", [])), false);
        let void = TSType::new_ts_void_keyword(SPAN, ast);
        let undefined = TSType::new_ts_undefined_keyword(SPAN, ast);
        (signal, reference(ast, "AsyncGenerator", [value, void, undefined]))
    } else {
        let signal = property(ast, "signal", reference(ast, "AbortSignal", []));
        let options = TSType::new_ts_type_literal(SPAN, [signal], ast);
        (parameter(ast, "options", Some(options), true), reference(ast, "Promise", [value]))
    };
    let request = parameter(ast, "request", Some(request), false);
    let kind = FormalParameterKind::FormalParameter;
    let parameters = FormalParameters::boxed(SPAN, kind, [request, last], None, ast);
    let returned = TSTypeAnnotation::boxed(SPAN, returned, ast);
    let id = BindingIdentifier::new(SPAN, function, ast);
    let declared = FunctionType::TSDeclareFunction;
    let function = Declaration::new_function_declaration(
        SPAN,
        declared,
        Some(id),
        false,
        false,
        true,
        None,
        None,
        parameters,
        Some(returned),
        None,
        ast,
    );
    Statement::new_export_declaration(span, function, ast)
}

/// A module's `index.js`, a function calling each of `procedures` through `@taba-build/rpc`.
fn script(procedures: &[&procedure::Declaration]) -> String {
    let allocator = Allocator::default();
    let ast = AstBuilder::new(&allocator);
    let mut comments = Comments::default();
    let marker = comments.line(MARKER);
    let sessions: BTreeSet<_> = procedures.iter().map(|procedure| session(procedure)).collect();
    let import = import(&ast, marker, ImportOrExportKind::Value, sessions);
    let callers = procedures.iter().map(|procedure| caller(&ast, procedure));
    let program = comments.program(&ast, SourceType::mjs(), iter::once(import).chain(callers));
    Codegen::new().build(&program).code
}

/// `export const buy = (request, options) => $tryCall("game_types::shop::Buy", request, options);`
fn caller<'a>(ast: &AstBuilder<'a>, procedure: &procedure::Declaration) -> Statement<'a> {
    let named = (procedure.named)();
    let function = ast.allocator().alloc_str(&function_name(named));
    let last = match procedure.reply {
        ReplyShape::Once(_) => "options",
        ReplyShape::Strand(_) => "signal",
    };
    let wire = ast.allocator().alloc_str(&named.path());
    let wire = Expression::new_string_literal(SPAN, wire, None, ast);
    let request = Expression::new_identifier(SPAN, "request", ast);
    let argument = Expression::new_identifier(SPAN, last, ast);
    let arguments = [wire, request, argument].map(Argument::from);
    let (_, local) = session(procedure);
    let callee = Expression::new_identifier(SPAN, local, ast);
    let call = Expression::new_call_expression(SPAN, callee, None, arguments, false, ast);
    let kind = FormalParameterKind::ArrowFormalParameters;
    let parameters = [parameter(ast, "request", None, false), parameter(ast, last, None, false)];
    let parameters = FormalParameters::boxed(SPAN, kind, parameters, None, ast);
    let body = ArrowFunctionBody::from(call);
    let arrow =
        Expression::new_arrow_function_expression(SPAN, false, None, parameters, None, body, ast);
    let id = BindingPattern::new_binding_identifier(SPAN, function, ast);
    let constant = VariableDeclarator::new(SPAN, id, None, Some(arrow), false, ast);
    let kind = VariableDeclarationKind::Const;
    let constant = Declaration::new_variable_declaration(SPAN, kind, [constant], false, ast);
    Statement::new_export_declaration(SPAN, constant, ast)
}

/// The `@taba-build/rpc` function that sends a procedure, and its name in a script.
///
/// The `$` keeps a procedure called `Call` from shadowing it.
fn session(procedure: &procedure::Declaration) -> (&'static str, &'static str) {
    match (procedure.reply, fallible(procedure)) {
        (ReplyShape::Once(_), false) => ("call", "$call"),
        (ReplyShape::Once(_), true) => ("tryCall", "$tryCall"),
        (ReplyShape::Strand(_), false) => ("subscribe", "$subscribe"),
        (ReplyShape::Strand(_), true) => ("trySubscribe", "$trySubscribe"),
    }
}

/// `import { call as $call } from "@taba-build/rpc";`, with each `(imported, local)` pair.
fn import<'a>(
    ast: &AstBuilder<'a>,
    span: Span,
    kind: ImportOrExportKind,
    names: impl IntoIterator<Item = (&'a str, &'a str)>,
) -> Statement<'a> {
    let specifiers = names.into_iter().map(|(imported, local)| {
        let imported = ModuleExportName::new_identifier_name(SPAN, imported, ast);
        let local = BindingIdentifier::new(SPAN, local, ast);
        let value = ImportOrExportKind::Value;
        ImportDeclarationSpecifier::new_import_specifier(SPAN, imported, local, value, ast)
    });
    let specifiers = ArenaVec::from_iter_in(specifiers, ast);
    let source = StringLiteral::new(SPAN, "@taba-build/rpc", None, ast);
    Statement::new_import_declaration(span, Some(specifiers), source, None, None, kind, ast)
}

/// A parameter named `name`, typed in a declarations file.
fn parameter<'a>(
    ast: &AstBuilder<'a>,
    name: &'a str,
    ty: Option<TSType<'a>>,
    optional: bool,
) -> FormalParameter<'a> {
    let pattern = BindingPattern::new_binding_identifier(SPAN, name, ast);
    let annotation = ty.map(|ty| TSTypeAnnotation::boxed(SPAN, ty, ast));
    FormalParameter::new(SPAN, [], pattern, annotation, None, optional, None, false, false, ast)
}

/// `name?: ty`, an optional property.
fn property<'a>(ast: &AstBuilder<'a>, name: &'a str, ty: TSType<'a>) -> TSSignature<'a> {
    let key = PropertyKey::new_static_identifier(SPAN, name, ast);
    let annotation = Some(TSTypeAnnotation::boxed(SPAN, ty, ast));
    TSSignature::new_ts_property_signature(SPAN, false, true, false, key, annotation, ast)
}

/// `Name<arguments>`.
fn reference<'a, const N: usize>(
    ast: &AstBuilder<'a>,
    name: &'a str,
    arguments: [TSType<'a>; N],
) -> TSType<'a> {
    let name = TSTypeName::new_identifier_reference(SPAN, name, ast);
    let arguments = (N > 0).then(|| {
        let arguments = ArenaVec::from_array_in(arguments, ast);
        TSTypeParameterInstantiation::boxed(SPAN, arguments, ast)
    });
    TSType::new_ts_type_reference(SPAN, name, arguments, ast)
}

/// Writes `files` into `directory`, then deletes the files taba wrote there before but not now.
///
/// A file whose contents already match is left alone, and so is any file taba didn't write. Every
/// file is checked before any is written, so a refusal changes nothing.
fn write(directory: &Path, files: Vec<(PathBuf, String)>) -> Result<(), WriteError> {
    let mut stale = marked(directory)?;
    let mut changed = Vec::new();
    for (path, contents) in files {
        let path = directory.join(path);
        stale.remove(&path);
        match fs::read(&path) {
            Ok(current) if current == contents.as_bytes() => {}
            Ok(current) if !is_marked(&current) => return Err(WriteError::unmarked(&path)),
            Ok(_) => changed.push((path, contents)),
            Err(error) if error.kind() == io::ErrorKind::NotFound => changed.push((path, contents)),
            Err(error) => return Err(WriteError::io(&path, error)),
        }
    }
    for (path, contents) in changed {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|error| WriteError::io(parent, error))?;
        }
        fs::write(&path, contents).map_err(|error| WriteError::io(&path, error))?;
    }
    for path in stale {
        fs::remove_file(&path).map_err(|error| WriteError::io(&path, error))?;
    }
    Ok(())
}

/// The files taba wrote under `directory`, which may not exist yet.
fn marked(directory: &Path) -> Result<BTreeSet<PathBuf>, WriteError> {
    let mut marked = BTreeSet::new();
    let mut directories = vec![directory.to_path_buf()];
    while let Some(directory) = directories.pop() {
        let entries = match fs::read_dir(&directory) {
            Ok(entries) => entries,
            Err(error) if error.kind() == io::ErrorKind::NotFound => continue,
            Err(error) => return Err(WriteError::io(&directory, error)),
        };
        for entry in entries {
            let entry = entry.map_err(|error| WriteError::io(&directory, error))?;
            let path = entry.path();
            let kind = entry.file_type().map_err(|error| WriteError::io(&path, error))?;
            if kind.is_dir() {
                directories.push(path);
            } else if kind.is_file() && fs::read(&path).is_ok_and(|contents| is_marked(&contents)) {
                marked.insert(path);
            }
        }
    }
    Ok(marked)
}

/// Whether `contents` starts with taba's [`MARKER`].
fn is_marked(contents: &[u8]) -> bool {
    contents.strip_prefix(b"// ").is_some_and(|rest| rest.starts_with(MARKER.as_bytes()))
}

#[cfg(test)]
mod tests {
    use std::fs;

    use super::{MARKER, write};

    #[test]
    fn a_write_replaces_and_deletes_only_its_own_files() {
        let directory = std::env::temp_dir().join(format!("taba-client-{}", std::process::id()));
        let _ = fs::remove_dir_all(&directory);
        let marked = |contents: &str| format!("// {MARKER}\n{contents}\n");
        fs::create_dir_all(directory.join("shop")).unwrap();
        fs::write(directory.join("index.js"), marked("taba's, from before")).unwrap();
        fs::write(directory.join("notes.md"), "the app's own\n").unwrap();
        fs::write(directory.join("shop/index.js"), marked("a module since deleted")).unwrap();

        let refused = write(&directory, vec![("notes.md".into(), marked("taba's"))]).is_err();
        write(&directory, vec![("index.js".into(), marked("taba's"))]).unwrap();
        let files = ["index.js", "notes.md", "shop/index.js"].map(|file| {
            let contents = fs::read_to_string(directory.join(file)).ok();
            format!("{file}: {contents:?}")
        });
        fs::remove_dir_all(&directory).unwrap();
        insta::assert_snapshot!(format!("refused: {refused}\n{}", files.join("\n")), @r#"
        refused: true
        index.js: Some("// @generated by taba-build\ntaba's\n")
        notes.md: Some("the app's own\n")
        shop/index.js: None
        "#);
    }
}
